<?php
require __DIR__ . '/lib/bootstrap.php';
require __DIR__ . '/lib/i18n.php';

if (is_installed()) { header('Location: index.php'); exit; }

$checks = [
    'PHP ≥ 8.0' => version_compare(PHP_VERSION, '8.0.0', '>='),
    'cURL' => extension_loaded('curl'),
    'OpenSSL' => extension_loaded('openssl'),
    'PDO' => extension_loaded('pdo'),
    'PDO SQLite / MySQL' => extension_loaded('pdo_sqlite') || extension_loaded('pdo_mysql'),
    'mbstring' => extension_loaded('mbstring'),
    'data/ writable' => is_writable(DATA_DIR),
];
$allOk = !in_array(false, $checks, true);
$error = '';
$detected = detect_base_url();

if ($_SERVER['REQUEST_METHOD'] === 'POST' && $allOk) {
    $pw = (string)($_POST['password'] ?? '');
    $pw2 = (string)($_POST['password2'] ?? '');
    $url = rtrim(trim((string)($_POST['base_url'] ?? $detected)), '/');
    $driver = ($_POST['driver'] ?? 'sqlite') === 'mysql' ? 'mysql' : 'sqlite';
    if (strlen($pw) < 8) $error = t('pw_short');
    elseif ($pw !== $pw2) $error = t('pw_mismatch');
    else {
        $dbcfg = $driver === 'mysql' ? [
            'driver' => 'mysql',
            'host' => trim((string)$_POST['db_host']) ?: 'localhost',
            'port' => 3306,
            'name' => trim((string)$_POST['db_name']),
            'user' => trim((string)$_POST['db_user']),
            'pass' => (string)$_POST['db_pass'],
        ] : ['driver' => 'sqlite', 'path' => DATA_DIR . '/app.sqlite'];
        try {
            db($dbcfg);
            db_migrate();
            $cfg = ['app_key' => bin2hex(random_bytes(32)), 'db' => $dbcfg, 'installed_at' => gmdate('c')];
            $php = "<?php\n// Generated by the installer. Keep this file private.\nreturn " . var_export($cfg, true) . ";\n";
            if (file_put_contents(CONFIG_FILE, $php) === false) throw new RuntimeException(t('not_writable'));
            @chmod(CONFIG_FILE, 0640);
            setting_set('admin_pass_hash', password_hash($pw, PASSWORD_DEFAULT));
            setting_set('admin_pass_ver', '1');
            setting_set('base_url', $url);
            setting_set('allow_dcr', '1');
            setting_set('access_token_ttl', '86400');
            if (!is_dir(STAGING_DIR)) @mkdir(STAGING_DIR, 0775, true);
            app_start_session();
            session_regenerate_id(true);
            $_SESSION['admin'] = true;
            $_SESSION['admin_ver'] = '1';
            header('Location: index.php#/welcome');
            exit;
        } catch (Throwable $e) {
            @unlink(CONFIG_FILE);
            $error = 'Database error: ' . $e->getMessage();
        }
    }
}

page_head(t('install_title'));
?>
<main class="auth-card wide">
  <div class="auth-top">
    <div class="brand"><img src="assets/img/logo.svg" alt=""><span>YT Connector</span></div>
    <?= lang_switch() ?>
  </div>
  <h1><?= h(t('install_title')) ?></h1>
  <p class="muted"><?= h(t('install_sub')) ?></p>

  <div class="req-grid">
    <?php foreach ($checks as $name => $ok): ?>
      <div class="req <?= $ok ? 'ok' : 'bad' ?>"><span class="dot"></span><?= h($name) ?></div>
    <?php endforeach; ?>
  </div>
  <?php if (!$checks['data/ writable']): ?><div class="alert error"><?= h(t('not_writable')) ?></div><?php endif; ?>
  <?php if ($error): ?><div class="alert error"><?= h($error) ?></div><?php endif; ?>

  <form method="post" class="form" autocomplete="off">
    <div class="grid-2">
      <label class="field"><span><?= h(t('admin_password')) ?></span>
        <input type="password" name="password" required minlength="8"></label>
      <label class="field"><span><?= h(t('confirm_password')) ?></span>
        <input type="password" name="password2" required minlength="8"></label>
    </div>
    <label class="field"><span><?= h(t('site_url')) ?></span>
      <input type="url" name="base_url" value="<?= h($_POST['base_url'] ?? $detected) ?>" required dir="ltr">
      <small><?= h(t('site_url_hint')) ?></small></label>

    <fieldset class="field">
      <span><?= h(t('database')) ?></span>
      <div class="seg">
        <label><input type="radio" name="driver" value="sqlite" <?= extension_loaded('pdo_sqlite') ? 'checked' : 'disabled' ?>> <?= h(t('db_sqlite')) ?></label>
        <label><input type="radio" name="driver" value="mysql" <?= !extension_loaded('pdo_sqlite') ? 'checked' : '' ?>> <?= h(t('db_mysql')) ?></label>
      </div>
    </fieldset>
    <div class="grid-2 mysql-fields">
      <label class="field"><span><?= h(t('db_host')) ?></span><input name="db_host" value="localhost" dir="ltr"></label>
      <label class="field"><span><?= h(t('db_name')) ?></span><input name="db_name" dir="ltr"></label>
      <label class="field"><span><?= h(t('db_user')) ?></span><input name="db_user" dir="ltr"></label>
      <label class="field"><span><?= h(t('db_pass')) ?></span><input type="password" name="db_pass" dir="ltr"></label>
    </div>
    <button class="btn primary block" <?= $allOk ? '' : 'disabled' ?>><?= h(t('install_btn')) ?></button>
  </form>
</main>
<script>
  const f = document.querySelector('.mysql-fields');
  const sync = () => f.style.display = document.querySelector('input[name=driver]:checked')?.value === 'mysql' ? '' : 'none';
  document.querySelectorAll('input[name=driver]').forEach(r => r.addEventListener('change', sync)); sync();
</script>
</body></html>
